func T(lang, key string) string {
	if m, ok := dict[lang]; ok {
		if v, ok := m[key]; ok {
			return v
		}
	}
	if v, ok := dict["en"][key]; ok {
		return v
	}
	return key
}

func Valid(lang string) bool {
	_, ok := dict[lang]
	return ok
}

// Weekdays — короткие названия дней для шапки сетки, с понедельника.
func Weekdays(lang string) [7]string {
	switch lang {
	case "ru":
		return [7]string{"Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"}
	case "de":
		return [7]string{"Mo", "Di", "Mi", "Do", "Fr", "Sa", "So"}
	default:
		return [7]string{"Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"}
	}
}
